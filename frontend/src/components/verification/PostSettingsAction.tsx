import { useCallback, useState } from 'react'

import { useAuthUser } from '../../features/auth/authContext'
import { canPostToCore } from '../../lib/auth'
import { PostSettingsModal } from './PostSettingsModal'

/**
 * The workspace header's "Post Settings" button and its dialog (D19).
 *
 * Shown only to accounts that hold every verification permission — the same
 * rule the server enforces — because a Loan Officer opening a dialog whose
 * saves would be refused only finds out too late. The gear is inline SVG so
 * the button needs no icon package.
 */
export function PostSettingsAction() {
  const user = useAuthUser()
  const [open, setOpen] = useState(false)
  const onClose = useCallback(() => setOpen(false), [])

  if (!canPostToCore(user)) return null

  return (
    <>
      <button className="btn-secondary flex items-center gap-1.5 py-1.5" onClick={() => setOpen(true)} type="button">
        <svg
          aria-hidden="true"
          className="h-4 w-4"
          fill="none"
          stroke="currentColor"
          strokeLinecap="round"
          strokeLinejoin="round"
          strokeWidth={2}
          viewBox="0 0 24 24"
        >
          <circle cx="12" cy="12" r="3" />
          <path d="M19.4 15a1.65 1.65 0 0 0 .33 1.82l.06.06a2 2 0 0 1 0 2.83 2 2 0 0 1-2.83 0l-.06-.06a1.65 1.65 0 0 0-1.82-.33 1.65 1.65 0 0 0-1 1.51V21a2 2 0 0 1-2 2 2 2 0 0 1-2-2v-.09A1.65 1.65 0 0 0 9 19.4a1.65 1.65 0 0 0-1.82.33l-.06.06a2 2 0 0 1-2.83 0 2 2 0 0 1 0-2.83l.06-.06a1.65 1.65 0 0 0 .33-1.82 1.65 1.65 0 0 0-1.51-1H3a2 2 0 0 1-2-2 2 2 0 0 1 2-2h.09A1.65 1.65 0 0 0 4.6 9a1.65 1.65 0 0 0-.33-1.82l-.06-.06a2 2 0 0 1 0-2.83 2 2 0 0 1 2.83 0l.06.06a1.65 1.65 0 0 0 1.82.33H9a1.65 1.65 0 0 0 1-1.51V3a2 2 0 0 1 2-2 2 2 0 0 1 2 2v.09a1.65 1.65 0 0 0 1 1.51 1.65 1.65 0 0 0 1.82-.33l.06-.06a2 2 0 0 1 2.83 0 2 2 0 0 1 0 2.83l-.06.06a1.65 1.65 0 0 0-.33 1.82V9a1.65 1.65 0 0 0 1.51 1H21a2 2 0 0 1 2 2 2 2 0 0 1-2 2h-.09a1.65 1.65 0 0 0-1.51 1z" />
        </svg>
        Post Settings
      </button>
      {open ? <PostSettingsModal onClose={onClose} /> : null}
    </>
  )
}
